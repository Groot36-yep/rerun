# Titles that are about Christmas although their title doesn't say so; they count as Christmas
# movies for holiday channels and stay on the shelf the rest of the year.
EXTRA_CHRISTMAS_MOVIES = sorted(
    {(t, y) for t, y, k, _s in ESSENTIALS if k != "episode"}
    | {(v[0], v[1]) for v in TITLES.values() if v[3]})


def title_info(key: str) -> dict:
    t, y, kind, xmas, alt, years = TITLES[key]
    return {"key": key, "title": t, "year": y, "kind": kind, "christmas": xmas, "alt": alt, "years": [y, *years]}
